#!/usr/bin/env python3
"""Assemble the WebUI sources into the single embedded page.

    src/ui/src/index.html   skeleton (markup only — no CSS, no JS)
    src/ui/src/css/*.css    stylesheet layers, concatenated in file-name order
    src/ui/src/js/*.js      script layers, concatenated in file-name order

Outputs:

    src/ui/index.html       the assembled page — the dev-loop artifact that
                            `cell-app.exe --headless PORT --ui src/ui/index.html`
                            serves straight from disk (edit + refresh, no rebuild)
    src/cell-ui.hpp         the same page as a C++ raw string literal (the only
                            artifact the C++ build needs)

An output is only (re)written when its content changed, so the CMake build can
run this script before every build without triggering needless recompiles.

Usage:
    python build_ui.py            # both outputs
    python build_ui.py --html     # src/ui/index.html only (dev loop)
    python build_ui.py --check    # fail if an output is stale
"""
import pathlib
import sys

ROOT = pathlib.Path(__file__).resolve().parent
SRC = ROOT / "src/ui/src"
OUT_HTML = ROOT / "src/ui/index.html"
OUT_HPP = ROOT / "src/cell-ui.hpp"

BANNER = ("<!-- ============================================================\n"
          "     GENERATED by build_ui.py from src/ui/src/ — do not edit.\n"
          "     Edit src/ui/src/{index.html,css/*.css,js/*.js} and re-run the\n"
          "     builder. Dev loop (no rebuild, no regeneration):\n"
          "       cell-app.exe --headless 8787 --ui src/ui/index.html\n"
          "     ============================================================ -->")


def layer(folder: str, suffix: str) -> str:
    files = sorted((SRC / folder).glob("*" + suffix))
    if not files:
        raise SystemExit(f"build_ui: no {suffix} sources in {SRC / folder}")
    chunks = []
    for f in files:
        chunks.append(f"/* ==== {folder}/{f.name} " + "=" * max(4, 60 - len(f.name)) + " */")
        # utf-8-sig: a BOM in a layer would land inside the assembled page
        chunks.append(f.read_text(encoding="utf-8-sig").rstrip())
    return "\n\n".join(chunks) + "\n"


def build() -> str:
    skeleton = (SRC / "index.html").read_text(encoding="utf-8-sig").replace("\r\n", "\n")
    css = layer("css", ".css")
    js = layer("js", ".js")
    if "/*@css*/" not in skeleton or "/*@js*/" not in skeleton:
        raise SystemExit("build_ui: skeleton is missing the /*@css*/ or /*@js*/ marker")
    page = skeleton.replace("/*@css*/", css).replace("/*@js*/", js)
    # the banner goes after the doctype so the page still parses identically
    if page.startswith("<!DOCTYPE html>"):
        head, _, rest = page.partition("\n")
        page = head + "\n" + BANNER + "\n" + rest
    return page.replace("\r\n", "\n")


def hpp(page: str) -> str:
    delim = "CELLUI"
    n = 0
    while (")" + delim + '"') in page:
        n += 1
        delim = f"CELLUI{n}"
        if n > 100:
            raise SystemExit("build_ui: cannot find a safe raw-string delimiter")
    return ("// cell-ui.hpp — GENERATED by build_ui.py from src/ui/src/.\n"
            "// Do not edit by hand: edit src/ui/src/{index.html,css/*.css,js/*.js}\n"
            "// and re-run `python build_ui.py` (the CMake build does it).\n"
            "#pragma once\n"
            "\n"
            "namespace app\n"
            "{\n"
            f'    inline constexpr const char *kUiHtml = R"{delim}(' + page + ')' + delim + '";\n'
            "} // namespace app\n")


def save(path: pathlib.Path, text: str) -> None:
    """Write text only when it differs, so a no-op keeps timestamps intact."""
    if path.is_file() and path.read_text(encoding="utf-8") == text:
        print(f"build_ui: untouched {path.relative_to(ROOT)}")
        return
    # newline="\n" keeps generated files LF-only on every platform
    with open(path, "w", encoding="utf-8", newline="\n") as f:
        f.write(text)
    print(f"build_ui: -> {path.relative_to(ROOT)}")


def main() -> int:
    args = set(sys.argv[1:])
    page = build()
    if "--check" in args:
        stale = []
        if not OUT_HTML.is_file() or OUT_HTML.read_text(encoding="utf-8") != page:
            stale.append(str(OUT_HTML.relative_to(ROOT)))
        if not OUT_HPP.is_file() or OUT_HPP.read_text(encoding="utf-8") != hpp(page):
            stale.append(str(OUT_HPP.relative_to(ROOT)))
        if stale:
            print("build_ui: stale output(s): " + ", ".join(stale), file=sys.stderr)
            return 1
        print("build_ui: up to date")
        return 0
    if "--html" not in args:
        save(OUT_HPP, hpp(page))
    save(OUT_HTML, page)
    return 0


if __name__ == "__main__":
    sys.exit(main())
